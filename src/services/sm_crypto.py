# SM2 非对称加密 (国密椭圆曲线)
# ═══════════════════════════════════════════
def sm2_keygen() -> dict:
    """SM2 密钥对生成 (用 SECP256R1 占位, 生产环境需用真实 SM2 曲线)"""
    from cryptography.hazmat.primitives.asymmetric import ec
    key = ec.generate_private_key(ec.SECP256R1())
    pub = key.public_key()
    pub_bytes = pub.public_bytes(
        encoding=ec.Encoding.X962,
        format=ec.PublicFormat.UncompressedPoint
    )
    return {"private": key, "public": pub_bytes.hex()}

def sm2_sign(private_key, data: bytes) -> bytes:
    """SM2 签名"""
    from cryptography.hazmat.primitives import hashes
    return private_key.sign(data, ec.ECDSA(hashes.SHA256()))

def sm2_verify(public_key, data: bytes, signature: bytes) -> bool:
    """SM2 验签"""
    from cryptography.hazmat.primitives import hashes
    try:
        public_key.verify(signature, data, ec.ECDSA(hashes.SHA256()))
        return True
    except: return False


