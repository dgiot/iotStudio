def generate_device_key(device_id: str) -> str:
    """生成设备密钥 (SM4 16字节)"""
    seed = f"dgiot_sm4_{device_id}_{os.urandom(8).hex()}"
    return hashlib.sha256(seed.encode()).digest()[:16].hex()

def sm3_checksum(data: bytes) -> str:
    """SM3 完整性校验"""
    return sm3_hash(data)

def encrypt_payload(payload: bytes, key_hex: str) -> str:
    """SM4 加密载荷"""
    return sm4_encrypt(bytes.fromhex(key_hex), payload).hex()

def decrypt_payload(ciphertext_hex: str, key_hex: str) -> bytes:
    """SM4 解密载荷"""
    return sm4_decrypt(bytes.fromhex(key_hex), bytes.fromhex(ciphertext_hex))
