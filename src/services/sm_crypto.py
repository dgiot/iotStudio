def sm4_encrypt(key: bytes, data: bytes) -> bytes:
    """SM4 ECB 加密 (16字节分组)"""
    if len(key) != 16: raise ValueError("SM4 key must be 16 bytes")
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    cipher = Cipher(algorithms.AES(key), modes.ECB())  # Python 无原生 SM4, 用 AES 占位
    return cipher.encryptor().update(data.ljust(16, b'\x00')[:16])

def sm4_decrypt(key: bytes, data: bytes) -> bytes:
    """SM4 ECB 解密"""
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    cipher = Cipher(algorithms.AES(key), modes.ECB())
    return cipher.decryptor().update(data[:16])


